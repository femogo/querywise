"""AST-based SQL guardrail using sqlglot (Defense-in-Depth Layer 2)."""

from __future__ import annotations

import sqlglot
from sqlglot import exp
from sqlglot.errors import ParseError

ALLOWED_TABLES: frozenset[str] = frozenset(
    {
        "categories",
        "products",
        "customers",
        "orders",
        "order_items",
        "support_tickets",
    }
)

BLOCKED_COLUMNS: frozenset[str] = frozenset(
    {
        "password_hash",
        "tax_id",
        "secret_token_ref",
    }
)

BLOCKED_SCHEMAS: frozenset[str] = frozenset(
    {
        "pg_catalog",
        "information_schema",
        "pg_toast",
    }
)

TABLES_WITH_PII: frozenset[str] = frozenset({"customers"})


class SQLGuardrailError(ValueError):
    """Raised when a SQL query violates security or resource policies."""


def _extract_limit_value(limit_expr: exp.Limit | None) -> int | None:
    """Return integer value of a LIMIT clause if present and literal."""
    if limit_expr is None or limit_expr.expression is None:
        return None
    if isinstance(limit_expr.expression, exp.Literal) and limit_expr.expression.is_int:
        return int(limit_expr.expression.this)
    raise SQLGuardrailError("LIMIT clause must be a positive integer literal.")


def validate_and_rewrite_sql(sql: str, max_rows: int = 100) -> str:
    """Validate SQL AST in Postgres dialect and enforce a safe LIMIT.

    Args:
        sql: Raw SQL string generated by the LLM.
        max_rows: Maximum number of rows allowed to be returned.

    Returns:
        Sanitized PostgreSQL query string with enforced LIMIT.

    Raises:
        SQLGuardrailError: If syntax is invalid, non-SELECT, or accesses
            disallowed tables, schemas, or PII columns.
    """
    if not sql or not sql.strip():
        raise SQLGuardrailError("SQL query cannot be empty.")

    try:
        statements = sqlglot.parse(sql, read="postgres")
    except ParseError as exc:
        raise SQLGuardrailError(f"Invalid PostgreSQL syntax: {exc}") from exc

    statements = [stmt for stmt in statements if stmt is not None]
    if len(statements) != 1:
        raise SQLGuardrailError(f"Exactly one SQL statement is required; got {len(statements)}.")

    tree = statements[0]
    if not isinstance(tree, exp.Select):
        raise SQLGuardrailError(
            f"Only SELECT statements are allowed; got {tree.__class__.__name__}."
        )

    if tree.args.get("into") is not None:
        raise SQLGuardrailError("SELECT INTO is not allowed.")

    cte_names: set[str] = {
        cte.alias_or_name.lower() for cte in tree.find_all(exp.CTE) if cte.alias_or_name
    }

    referenced_tables: set[str] = set()
    for table in tree.find_all(exp.Table):
        schema_name = (table.db or "").lower()
        table_name = (table.name or "").lower()

        if schema_name and schema_name not in {"public"}:
            if schema_name in BLOCKED_SCHEMAS or schema_name.startswith("pg_"):
                raise SQLGuardrailError(f"Access to system schema '{schema_name}' is forbidden.")
            raise SQLGuardrailError(f"Access to schema '{schema_name}' is not allowed.")

        if table_name.startswith("pg_") or table_name in BLOCKED_SCHEMAS:
            raise SQLGuardrailError(f"Access to system table '{table_name}' is forbidden.")

        if table_name in cte_names:
            continue

        if table_name not in ALLOWED_TABLES:
            raise SQLGuardrailError(f"Table '{table_name}' is not in the allowed business tables.")
        referenced_tables.add(table_name)

    if not referenced_tables:
        raise SQLGuardrailError("Query must reference at least one allowed table.")

    if referenced_tables & TABLES_WITH_PII and list(tree.find_all(exp.Star)):
        raise SQLGuardrailError(
            "Wildcard '*' is forbidden when querying tables with PII columns "
            f"({', '.join(sorted(TABLES_WITH_PII))}). Select explicit safe columns."
        )

    for column in tree.find_all(exp.Column):
        col_name = (column.name or "").lower()
        if col_name in BLOCKED_COLUMNS:
            raise SQLGuardrailError(f"Access to sensitive PII column '{col_name}' is forbidden.")

    existing_limit = _extract_limit_value(tree.args.get("limit"))
    if existing_limit is None or existing_limit > max_rows:
        tree.set("limit", exp.Limit(expression=exp.Literal.number(max_rows)))
    elif existing_limit <= 0:
        raise SQLGuardrailError("LIMIT must be greater than zero.")

    return tree.sql(dialect="postgres")
